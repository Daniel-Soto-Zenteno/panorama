const { launchBrowser } = require('./browser-runtime.cjs');
const fs = require('fs');
(async () => {
 const browser = await launchBrowser();
 const context = await browser.newContext({viewport:{width:1366,height:768},locale:'es-CL'});
 const page = await context.newPage(); const checks=[]; const errors=[];
 page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8011/',{waitUntil:'networkidle'});
 await page.screenshot({path:'docs/evidencias/C01-explorar-desktop.png',fullPage:true});
 checks.push({id:'CP29',test:'Mapa y lista en escritorio 1366x768',observed:await page.locator('.activity').count(),passed:await page.locator('.activity').count()>=4});
 await page.goto('http://127.0.0.1:8011/activity/1/');
 await page.screenshot({path:'docs/evidencias/C02-ficha.png',fullPage:true});
 await page.goto('http://127.0.0.1:8011/community/1/');
 await page.screenshot({path:'docs/evidencias/C03-foro.png',fullPage:true});
 await page.setViewportSize({width:360,height:800});
 const sizes=[];
 for(const url of ['/','/activity/1/','/community/1/','/account/register/']){
  await page.goto('http://127.0.0.1:8011'+url);
  const size=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth, viewport:innerWidth}));
  sizes.push({url,...size});
 }
 await page.goto('http://127.0.0.1:8011/');
 await page.screenshot({path:'docs/evidencias/C04-explorar-movil.png',fullPage:true});
 checks.push({id:'CP30',test:'Sin desbordamiento a 360x800',observed:sizes,passed:sizes.every(s=>s.scroll<=s.viewport)});
 const fallback=await context.newPage();
 await fallback.route(/unpkg\.com|tile\.openstreetmap\.org/,route=>route.abort());
 await fallback.goto('http://127.0.0.1:8011/');
 await fallback.screenshot({path:'docs/evidencias/C05-sin-cartografia.png',fullPage:true});
 checks.push({id:'CP31',test:'Fallo de cartografía conserva lista y ficha',observed:await fallback.locator('#map-status').innerText(),passed:await fallback.locator('.activity').count()>=4 && (await fallback.locator('#map-status').innerText()).includes('no está disponible')});
 const creds=Object.fromEntries(fs.readFileSync('.demo-credentials.txt','utf8').replace(/^\uFEFF/,'').split(/\r?\n/).filter(l=>l.includes(': ')).map(l=>l.split(': ')));
 await page.setViewportSize({width:1366,height:768});
 await page.goto('http://127.0.0.1:8011/account/login/');
 await page.locator('#id_username').fill('demo_vecina');await page.locator('#id_password').fill(creds.demo_vecina);await page.getByRole('button',{name:'Continuar'}).click();
 await page.goto('http://127.0.0.1:8011/propose/actividad/');
 await page.locator('#id_titulo').fill('Encuentro de lectura vecinal');await page.locator('#id_descripcion').fill('Propuesta ficticia creada durante la prueba de extremo a extremo.');
 await page.locator('#id_categoria').selectOption('Cultura');await page.locator('#id_comunidad').selectOption('1');await page.locator('#id_lugar').selectOption('1');
 await page.locator('#id_fecha_hora').fill('2027-02-15T17:00');await page.locator('#id_fin').fill('2027-02-15T19:00');
 await page.screenshot({path:'docs/evidencias/C06-propuesta.png',fullPage:true});
 await page.getByRole('button',{name:'Guardar propuesta'}).click();
 const link=page.getByRole('link',{name:'Encuentro de lectura vecinal'}).last();
 const href=await link.getAttribute('href');const pk=href.split('/')[2];
 await page.screenshot({path:'docs/evidencias/C07-mis-propuestas.png',fullPage:true});
 await page.getByRole('button',{name:'Salir',exact:true}).click();
 await page.goto('http://127.0.0.1:8011/account/login/');await page.locator('#id_username').fill('demo_moderador');await page.locator('#id_password').fill(creds.demo_moderador);await page.getByRole('button',{name:'Continuar'}).click();
 await page.goto(`http://127.0.0.1:8011/moderation/actividad/${pk}/`);await page.locator('#id_motivo').fill('Propuesta ficticia revisada para la evaluación');await page.getByRole('button',{name:'Registrar decisión'}).click();
 await page.screenshot({path:'docs/evidencias/C08-moderacion.png',fullPage:true});
 await page.goto(`http://127.0.0.1:8011/activity/${pk}/`);await page.getByRole('button',{name:'Quiero asistir'}).click();
 const text=await page.locator('main').innerText();
 await page.screenshot({path:'docs/evidencias/C09-asistencia.png',fullPage:true});
 checks.push({id:'CP32',test:'Navegador: propuesta, aprobación y asistencia',observed:{pk,approved:text.includes('APROBADO'),attendance:text.includes('1 intenciones')},passed:text.includes('APROBADO')&&text.includes('1 intenciones')});
 await page.goto('http://127.0.0.1:8011/community/1/');await page.locator('#id_texto').fill('Mensaje ficticio publicado durante la prueba de navegador.');await page.getByRole('button',{name:'Publicar',exact:true}).click();
 const post=page.locator('article').filter({hasText:'Mensaje ficticio publicado durante la prueba de navegador.'}).first();await post.locator('textarea').fill('Respuesta de demostración.');await post.getByRole('button',{name:'Comentar',exact:true}).click();
 checks.push({id:'CP33',test:'Navegador: publicación y comentario',observed:await page.getByText('Respuesta de demostración.',{exact:true}).count(),passed:await page.getByText('Respuesta de demostración.',{exact:true}).count()>0});
 await page.screenshot({path:'docs/evidencias/C10-foro-interaccion.png',fullPage:true});
 fs.writeFileSync('docs/evidencias/navegador.json',JSON.stringify({browser:await browser.version(),checks,errors},null,2));
 console.log(JSON.stringify({checks,errors}));await browser.close();
 if(checks.some(c=>!c.passed)||errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
